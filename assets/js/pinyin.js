  // 构建 char → letter 映射（延迟构建，首次查询时才建）
  let map = null;

  function buildMap() {
    map = Object.create(null);
    Object.keys(GROUPS).forEach((letter) => {
      const str = GROUPS[letter];
      if (!str) return;
      for (let i = 0; i < str.length; i++) {
        const ch = str[i];
        if (!map[ch]) map[ch] = letter; // 多音字取首次出现的读音
      }
    });
  }

  /**
   * 取字符串的拼音首字母串
   * 汉字取首字母，英文字母原样保留并小写，其它字符丢弃
   * @param {string} str
   * @returns {string}
   */
  function initials(str) {
    if (!map) buildMap();
    let out = '';
    const s = String(str || '');
    for (let i = 0; i < s.length; i++) {
      const ch = s[i];
      if (/[a-zA-Z0-9]/.test(ch)) {
        out += ch.toLowerCase();
      } else if (/[\u4e00-\u9fa5]/.test(ch)) {
        const l = map[ch];
        if (l) out += l;
      }
    }
    return out;
  }

  /**
   * 判断 query 是否匹配 target（支持中文包含 / 拼音首字母 / 英文包含）
   * @param {string} target 被搜索的文本
   * @param {string} query 已转小写的查询词
   * @returns {{match:boolean, viaInitials:boolean, viaPinyinFull:boolean}}
   */
  function match(target, query) {
    const t = String(target || '').toLowerCase();
    const q = String(query || '').toLowerCase();
    if (!q) return { match: true, viaInitials: false, viaPinyinFull: false };

    if (t.indexOf(q) >= 0) return { match: true, viaInitials: false, viaPinyinFull: false };

    // 拼音首字母匹配
    const ini = initials(t);
    if (ini && ini.indexOf(q) >= 0) return { match: true, viaInitials: true, viaPinyinFull: false };

    return { match: false, viaInitials: false, viaPinyinFull: false };
  }

  function isReady() {
    return !!map;
  }

